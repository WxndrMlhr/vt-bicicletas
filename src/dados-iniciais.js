// Categoriza automaticamente pelo nome do item, so pra organizar a listagem.
function categorizar(nome) {
  const n = nome.toLowerCase();
  if (n.startsWith('bicicleta')) return 'Bicicleta completa';
  if (n.startsWith('quadro') || n.startsWith('garfo')) return 'Quadro';
  // Transmissao vem antes de Rodas: "roda livre" e peca de transmissao
  // e cairia na regra de "roda " se a ordem fosse invertida.
  if (n.match(/roda livre|catraca|c\u00e2mbio|corrente|engrenagem|coroa|pedivela|movimento central|movimento de dire\u00e7\u00e3o|movimento dire\u00e7\u00e3o|roldana|bra\u00e7o esquerdo|caixa de dire\u00e7\u00e3o/)) return 'Transmiss\u00e3o';
  if (n.match(/freio|pastilha|sapata|cabo de freio/)) return 'Freios';
  if (n.match(/aro |cubo|raio|roda |pneu|c\u00e2mara|niple/)) return 'Rodas';
  return 'Acess\u00f3rios';
}

